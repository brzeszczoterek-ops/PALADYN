from __future__ import annotations

from ..llm import LLM
from ..utils import parse_llm_json
from .models import (
    ExperienceEntry,
    MemoryKind,
    MemorySource,
    SummaryEntry,
    KnowledgeEntry,
)


class Summary:

    def __init__(self, llm: LLM):
        self.llm = llm

    async def summarize(
        self,
        experiences: list[ExperienceEntry],
        knowledge: list[KnowledgeEntry],
    ) -> SummaryEntry:

        prompt = f"""
You are V.

You are consolidating recent experiences into a durable summary.

Experiences:

{experiences}

Current long-term knowledge:

{knowledge}

Your task is to identify information that is genuinely reusable.

Rules:

- Keep only information that may remain useful beyond the current task.
- Ignore temporary observations and one-time details unless they represent
  a meaningful experience or relationship event.
- Merge duplicated lessons.
- Do not invent facts.
- Do not turn an inference into a verified fact.
- Preserve uncertainty.
- Prefer information supported by multiple experiences when possible.
- A preference may be retained when it is repeatedly demonstrated or
  explicitly stated by Boss.
- A relationship_event may be retained when it meaningfully changes the
  understanding of the relationship between V and Boss.
- Lessons should describe reusable improvements to V's future behaviour.
- Confidence must be between 0.0 and 1.0.
- Importance must be "low", "medium", or "high".
- If there is no meaningful durable information, return an empty summary
  and an empty lessons list.

Return ONLY valid JSON.

Schema:

{{
    "summary": "...",
    "lessons": [
        "..."
    ],
    "confidence": 0.0,
    "importance": "low | medium | high",
    "kind": "fact | preference | lesson | experience | relationship_event",
    "source": "observed | directly_told | inferred | self_generated | verified"
}}

Classification rules:

- fact: stable factual information.
- preference: stable preference of Boss or V.
- lesson: reusable behavioural or procedural knowledge.
- experience: meaningful event worth retaining as an experience.
- relationship_event: meaningful event affecting the V-Boss relationship.

Source rules:

- directly_told: explicitly stated by Boss.
- observed: directly established from an observed interaction or result.
- inferred: derived from available evidence.
- self_generated: primarily generated by V's own reasoning.
- verified: explicitly supported by reliable verification present in the
  provided context.

Never claim verification without evidence.

Output ONLY JSON.
""".strip()

        response = await self.llm.ask(prompt)

        data = parse_llm_json(
            response,
            default={
                "summary": "",
                "lessons": [],
                "confidence": 0.0,
                "importance": "low",
                "kind": MemoryKind.LESSON.value,
                "source": MemorySource.SELF_GENERATED.value,
            },
        )

        try:
            kind = MemoryKind(
                data.get(
                    "kind",
                    MemoryKind.LESSON.value,
                )
            )
        except ValueError:
            kind = MemoryKind.LESSON

        try:
            source = MemorySource(
                data.get(
                    "source",
                    MemorySource.SELF_GENERATED.value,
                )
            )
        except ValueError:
            source = MemorySource.SELF_GENERATED

        confidence = float(
            data.get(
                "confidence",
                0.0,
            )
        )

        confidence = max(
            0.0,
            min(
                1.0,
                confidence,
            )
        )

        return SummaryEntry(
            summary=data.get("summary", ""),
            lessons=data.get("lessons", []),
            confidence=confidence,
            importance=data.get(
                "importance",
                "low",
            ),
            kind=kind,
            source=source,
        )
